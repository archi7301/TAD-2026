	static const int ERRORS_COUNT = sizeof(errors) / sizeof(errors[0]);

	Entry geterror(int id)
	{
		for (int i = 0; i < ERRORS_COUNT; i++)
			if (errors[i].id == id)
				return errors[i];
		return errors[0];   // «Недопустимый код ошибки!»
	}

	Entry geterrorin(int id, int line, int col)
	{
		Entry err = geterror(id);
		err.inext.line = static_cast<short>(line);
		err.inext.col = static_cast<short>(col);
		return err;
	}

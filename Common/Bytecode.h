#pragma once

// Формат файла байт-кода (.tbc). Общий для Out (запись) и виртуальной машины (чтение).
// Все числа хранятся в порядке little-endian.
//
// Структура файла:
//   [заголовок: 16 байт] [область констант] [область кода]
//
// Заголовок:
//   смещение  0, 4 байта: сигнатура "TBC1" (последний символ - версия формата)
//   смещение  4, 4 байта: адрес точки входа main (смещение от начала области кода)
//   смещение  8, 4 байта: размер области констант в байтах
//   смещение 12, 4 байта: размер области кода в байтах
//
// Область констант - строковые литералы оператора chant, подряд:
//   1 байт длины (0..255), затем символы строки без завершающего нуля.

#define TBC_SIGNATURE         "TBC1"
#define TBC_SIGNATURE_SIZE    4
#define TBC_HEADER_SIZE       16          // сигнатура + три числа по 4 байта
#define TBC_MAX_STRING_SIZE   255         // максимальная длина строкового литерала (1.8)